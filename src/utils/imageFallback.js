export const DEFAULT_PRODUCT_IMAGE = 'https://images.unsplash.com/photo-1545241047-6083a3684587?auto=format&fit=crop&w=800&q=80';

// Deterministically returns a unique, working image for each product based on category & productId
export const getUniqueProductImage = (product) => {
  if (!product) return DEFAULT_PRODUCT_IMAGE;

  // Check direct imageUrl property (e.g. from CartItemDTO / OrderItemDTO / Product)
  if (product.imageUrl && typeof product.imageUrl === 'string' && product.imageUrl.trim() !== '') {
    return product.imageUrl.trim();
  }

  // Use exact image URL provided in product.imageUrls array
  if (product.imageUrls && Array.isArray(product.imageUrls) && product.imageUrls.length > 0) {
    const primary = product.imageUrls[0];
    if (primary && typeof primary === 'string' && primary.trim() !== '') {
      return primary.trim();
    }
  }

  const categoryName = (product.categoryName || product.category || '').toUpperCase();
  const pid = Number(product.productId || product.id || 1);

  let targetPool = CATEGORY_IMAGE_POOLS['PLANTS'];
  for (const [key, pool] of Object.entries(CATEGORY_IMAGE_POOLS)) {
    if (categoryName.includes(key) || key.includes(categoryName)) {
      targetPool = pool;
      break;
    }
  }

  const index = Math.abs(pid - 1) % targetPool.length;
  return targetPool[index] || DEFAULT_PRODUCT_IMAGE;
};

export const handleImageError = (e, product) => {
  e.target.onerror = null; // Prevents infinite loops
  if (product) {
    const fallback = getUniqueProductImage(product);
    if (fallback && fallback !== e.target.src) {
      e.target.src = fallback;
      return;
    }
  }
  e.target.src = DEFAULT_PRODUCT_IMAGE;
};

